// Teste de fluxo: PARE em tela cheia, marcar passo, cadastrar paciente e consulta.
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const require = createRequire(import.meta.url);
const pw = ['playwright', '/opt/node-tools/node_modules/playwright'].reduce((m, c) => m || (() => { try { return require(c); } catch (e) { return null; } })(), null);
const root = path.dirname(fileURLToPath(import.meta.url));
const browser = await pw.chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })).newPage();
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(pathToFileURL(path.join(root, 'www', 'index.html')).href + '#/crianca/historia/3');
await page.waitForTimeout(300);
await page.click('#fab'); await page.waitForTimeout(200);
await page.screenshot({ path: path.join(root, 'screenshots', 'sinal_pare.png') });
await page.click('#sig-close');
await page.click('#st-done'); await page.waitForTimeout(200);
const done = await page.textContent('#st-done'); console.log('passo marcado:', done.trim());
await page.evaluate(() => { location.hash = '#/dentista/paciente/novo'; }); await page.waitForTimeout(300);
await page.fill('[data-k=nome]', 'João'); await page.fill('[data-k=idade]', '7'); await page.selectOption('[data-k=nivel]', '1');
await page.click('#p-save'); await page.waitForTimeout(400);
console.log('rota após salvar:', await page.evaluate(() => location.hash));
await page.selectOption('[data-c=degrau]', 'Abrir a boca'); await page.fill('[data-c=funcionou]', 'Fones e contagem');
await page.click('#c-add'); await page.waitForTimeout(300);
console.log('consultas na tela:', await page.$$eval('[data-del]', (b) => b.length));
await page.evaluate(() => { location.hash = '#/dentista/pacientes'; }); await page.waitForTimeout(300);
await page.screenshot({ path: path.join(root, 'screenshots', 'dentista_pacientes_com_dados.png') });
console.log('lista:', (await page.textContent('main')).includes('João') ? 'ok' : 'FALHOU');
if (errors.length) { console.error('ERROS:', errors); process.exitCode = 1; } else console.log('sem erros de JS');
await browser.close();
